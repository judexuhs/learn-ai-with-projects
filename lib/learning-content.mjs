export function getTopic(slug) {
  return topics.find((topic) => topic.slug === slug);
}

export function getLearningPath(slug) {
  return learningPaths.find((path) => path.slug === slug);
}

export function validateLearningContent(knownProjectSlugs) {
  const topicSlugs = new Set(topics.map((topic) => topic.slug));
  const projectSlugs = new Set(knownProjectSlugs);
  const missingTopics = learningPaths
    .flatMap((path) => path.steps.map((step) => step.topic))
    .filter((slug) => !topicSlugs.has(slug));
  const missingProjects = [
    ...topics.map((topic) => topic.relatedProject.slug),
    ...learningPaths.map((path) => path.project),
  ].filter((slug) => !projectSlugs.has(slug));

  return [...new Set([...missingTopics, ...missingProjects])];
}
